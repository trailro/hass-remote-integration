"""main_ha_version: what the declared main Home Assistant cannot parse is left out of discovery.

The main HA rejects the WHOLE device payload over one unknown platform or one unknown device class, so an entity
carrying `radon` (a device class of 2026.8) or a `date` entity (an MQTT platform of 2026.5) takes every other entity
of its device down with it on an older main HA.  The table (`ha_compat.json`, generated by `tools/gen_ha_compat.py`)
says when each of them appeared; these tests check the table itself, the filtering, the setting and the counters -
and, first of all, that a deployment which does not set it publishes exactly what it published before.
"""

import collections
